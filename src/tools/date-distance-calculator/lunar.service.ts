export const MIN_LUNAR_YEAR = 1900;
export const MAX_LUNAR_YEAR = 2100;

/** 1900-01-31 是农历 1900 年正月初一，整张表的时间原点 */
const BASE_MS = Date.UTC(1900, 0, 31);

export interface LunarInfo {
  /** 农历年（公历跨年后取农历年，如 2026-01-01 是乙巳年） */
  year: number;
  /** 农历月 1—12 */
  month: number;
  /** 农历日 1—30 */
  day: number;
  /** 这一天是否落在闰月里 */
  isLeap: boolean;
  /** 当年闰几月，无闰月为 0 */
  leapMonth: number;
  /** 「冬月」这类月名 */
  monthCn: string;
  /** 「十三」这类日名 */
  dayCn: string;
  /** 农历年干支，如 乙巳 */
  ganzhiYear: string;
  /** 农历月干支，如 戊子 */
  ganzhiMonth: string;
  /** 日干支，如 乙亥 */
  ganzhiDay: string;
  /** 生肖，如 蛇 */
  zodiac: string;
}

/** 1900-01-31 的干支是甲戌（60 甲子里的第 10 位，从 0 开始数） */
const GANZHI_EPOCH_OFFSET = 10;

function pad2(n: number): string {
  return n < 10 ? `0${n}` : String(n);
}

/**
 * 把 yyyy-mm-dd 解析成 UTC 零点的时间戳。
 *
 * 刻意用 UTC 构造：直接 new Date('2026-01-01') 在 UTC+8 下是当天 08:00，
 * 在 UTC-5 的机器上会变成前一天 19:00，跨时区机器上整天数都会差一天。
 * 这里统一按「日期字符串 → UTC 零点」处理，全站日历类工具都照这个来。
 */
export function parseDateMs(date: string): number {
  const [y, m, d] = date.split('-').map(Number);
  return Date.UTC(y, m - 1, d);
}

/** 把时间戳还原成 yyyy-mm-dd（用 UTC 读，跟 parseDateMs 对称） */
export function formatDateMs(ms: number): string {
  const d = new Date(ms);
  return `${d.getUTCFullYear()}-${pad2(d.getUTCMonth() + 1)}-${pad2(d.getUTCDate())}`;
}

/** 两个 yyyy-mm-dd 之间差几个自然日（后 − 前），按 UTC 整天算 */
export function diffDays(from: string, to: string): number {
  return Math.round((parseDateMs(to) - parseDateMs(from)) / 86400000);
}

/** 某年 12 个月（+ 可能的闰月）各自的天数；闰月插在 leapAt 月之后 */
function monthsOfYear(code: number): { month: number; leap: boolean; days: number }[] {
  const list: { month: number; leap: boolean; days: number }[] = [];
  for (let m = 1; m <= 12; m++) {
    list.push({ month: m, leap: false, days: code & (0x10000 >> m) ? 30 : 29 });
  }
  const leapAt = code & 0xf;
  if (leapAt > 0) {
    list.splice(leapAt, 0, {
      month: leapAt,
      leap: true,
      days: code & 0x10000 ? 30 : 29,
    });
  }
  return list;
}

/** 某农历年的总天数 */
function yearDays(code: number): number {
  return monthsOfYear(code).reduce((sum, m) => sum + m.days, 0);
}

function gan(index: number): string {
  return GAN[((index % 10) + 10) % 10];
}

function zhi(index: number): string {
  return ZHI[((index % 12) + 12) % 12];
}

function dayCn(day: number): string {
  if (day === 10) {
    return '初十';
  }
  if (day === 20) {
    return '二十';
  }
  if (day === 30) {
    return '三十';
  }
  const tens = day < 10 ? '初' : day < 20 ? '十' : '廿';
  return `${tens}${NUM_CN[day % 10]}`;
}

/** 干支年：天干 =(year−4)%10，地支 =(year−4)%12 */
function ganzhiOfYear(year: number): string {
  return `${gan(year - 4)}${zhi(year - 4)}`;
}

/**
 * 当前处在第几个「节」之后 —— 12 个节分别开启一个干支月。
 * 顺序：小寒(丑) 立春(寅) 惊蛰(卯) 清明(辰) 立夏(巳) 芒种(午)
 *       小暑(未) 立秋(申) 白露(酉) 寒露(戌) 立冬(亥) 大雪(子)
 *
 * 注意：干支月是按节气切的，不是按农历初一切的。比如 2026-01-15 农历还是冬月（子月），
 * 但已经过「小寒」，干支月就是丑月（己丑）—— 这就是原站显示「己丑」而不是「戊子」的原因。
 */
interface TermCursor {
  /** 最近一个「节」的下标，0 = 小寒，11 = 大雪 */
  idx: number;
  /** 该日处于第几天（1 月起算） */
  dayOfYear: number;
  /** 该年的「节」偏移表，表外年份为 null */
  row: number[] | null;
}

function termCursorOf(date: string): TermCursor {
  const [y] = date.split('-').map(Number);
  const dayOfYear = Math.round((parseDateMs(date) - Date.UTC(y, 0, 1)) / 86400000);
  const row = TERM_DAY_OFFSETS[y - MIN_LUNAR_YEAR] ?? null;
  if (!row) {
    return { idx: 11, dayOfYear, row: null };
  }
  if (dayOfYear < row[0]) {
    return { idx: 11, dayOfYear, row }; // 还没过小寒，仍是上一年「大雪」开启的那一月
  }
  let idx = 0;
  for (let i = 0; i < 12; i++) {
    if (dayOfYear >= row[i]) {
      idx = i;
    }
  }
  return { idx, dayOfYear, row };
}

/**
 * 干支月：先由「最近一个节」定地支（小寒→丑，立春→寅……大雪→子），再用五虎遁定天干。
 * 口诀：甲己之年丙作首，乙庚之年戊为头，丙辛之年庚上路，丁壬壬位顺行流，戊癸之年甲好求。
 *
 * 两个坑，都踩过：
 *   1. 地支要按节气换，不是按农历月初一换 —— 否则 2026-01-15（农历还是冬月）会算成子月而不是小寒后的丑月；
 *   2. 天干在「立春」换年，立春前要用上一年天干 —— 否则 1900-01-31 会算成己丑而不是丁丑。
 */
function ganzhiOfMonth(date: string): string {
  const { idx, dayOfYear, row } = termCursorOf(date);
  const [y] = date.split('-').map(Number);
  const branch = (idx + 1) % 12; // 小寒→丑(1)，大雪→子(0)，立春→寅(2)
  // 地支换回「这是第几月」：子月=冬月11、丑月=腊月12、寅月=正月1
  const ordinal = (branch + 10) % 12 + 1;
  const stemYear = row && dayOfYear >= row[1] ? y : y - 1; // row[1] 是立春
  const stemIndex = ((((stemYear - 4) % 10) + 10) % 10);
  const firstStem = (2 * stemIndex + 2) % 10;
  return `${gan(firstStem + ordinal - 1)}${zhi(branch)}`;
}

/**
 * 公历日干支：以 1900-01-01（甲戌）为原点，每天顺推一位。
 * 1900 年到目标日的总天数 + 10，再对 60 取模就是 60 甲子下标。
 */
function ganzhiOfDay(ms: number): string {
  const daysSince1900 = Math.round((ms - Date.UTC(1900, 0, 1)) / 86400000);
  const index = ((daysSince1900 + GANZHI_EPOCH_OFFSET) % 60 + 60) % 60;
  return `${gan(index)}${zhi(index)}`;
}

/**
 * 反查：农历正月初一对应的公历日期，如 2026 年春节 = 2026-02-17。
 * 只支持 1900—2100，区间外返回 null（调用方自己兜底）。
 */
export function lunarYearStart(lunarYear: number): string | null {
  if (lunarYear < MIN_LUNAR_YEAR || lunarYear > MAX_LUNAR_YEAR) {
    return null;
  }
  let ms = BASE_MS;
  for (let y = MIN_LUNAR_YEAR; y < lunarYear; y++) {
    ms += yearDays(LUNAR_YEAR_CODES[y - MIN_LUNAR_YEAR]) * 86400000;
  }
  return formatDateMs(ms);
}

/**
 * 查询某一天对应的农历信息。超出 1900—2100 返回 null ——
 * 前端据此提示「农历仅支持 1900—2100 年」，而不是给出错误的农历。
 */
export function getLunar(date: string): LunarInfo | null {
  const ms = parseDateMs(date);
  const offset = Math.round((ms - BASE_MS) / 86400000);
  if (offset < 0) {
    return null;
  }

  let year = MIN_LUNAR_YEAR;
  let rest = offset;
  while (year <= MAX_LUNAR_YEAR) {
    const code = LUNAR_YEAR_CODES[year - MIN_LUNAR_YEAR];
    const total = yearDays(code);
    if (rest < total) {
      break;
    }
    rest -= total;
    year += 1;
  }
  if (year > MAX_LUNAR_YEAR) {
    return null;
  }

  const code = LUNAR_YEAR_CODES[year - MIN_LUNAR_YEAR];
  const leapMonth = code & 0xf;
  const months = monthsOfYear(code);

  let carry = rest;
  let found = { month: 1, leap: false, days: 29 };
  for (const m of months) {
    if (carry < m.days) {
      found = m;
      break;
    }
    carry -= m.days;
  }

  return {
    year,
    month: found.month,
    day: carry + 1,
    isLeap: found.leap,
    leapMonth,
    // 闰月叫「闰八」，不是「八闰」也不是「八（闰）」，跟万年历一致
    monthCn: (found.leap ? '闰' : '') + MONTH_CN[found.month - 1],
    dayCn: dayCn(carry + 1),
    ganzhiYear: ganzhiOfYear(year),
    ganzhiMonth: ganzhiOfMonth(date),
    ganzhiDay: ganzhiOfDay(ms),
    zodiac: ZODIAC[(((year - 4) % 12) + 12) % 12],
  };
}

/** 公历星座，用公历月日查表，不涉及农历 */
export function getConstellation(date: string): string {
  const [, m, d] = date.split('-').map(Number);
  // 取「最后一条命中的分界线」而不是第一条：1 月 20 日同时满足 [1,1] 与 [1,20]，
  // 直接 return 会命中摩羯座。表是按日期升序排的，所以最后一条才是真分界。
  const hit = CONSTELLATIONS.filter(([mm, dd]) => m > mm || (m === mm && d >= dd));
  return hit.length > 0 ? hit[hit.length - 1][2] : CONSTELLATIONS[0][2];
}

/** 公历某年是不是闰年，页面上的「闰年 / 平年」用 */
export function isLeapYear(date: string): boolean {
  const y = Number(date.split('-')[0]);
  return (y % 4 === 0 && y % 100 !== 0) || y % 400 === 0;
}

/**
 * ISO 周数（周一为一周之始，公历 1 月第一个周四所在的周是第 1 周）。
 * 不自己写，交给 Intl，省得到年底边界算错。
 */
export function isoWeek(date: string): { week: number; year: number } {
  const [y, m, d] = date.split('-').map(Number);
  const dt = new Date(Date.UTC(y, m - 1, d));
  // 周四所在的年份才是 ISO 周所属年份
  const dayNum = dt.getUTCDay() || 7;
  dt.setUTCDate(dt.getUTCDate() + 4 - dayNum);
  const yearStart = new Date(Date.UTC(dt.getUTCFullYear(), 0, 1));
  const week = Math.ceil(((dt.getTime() - yearStart.getTime()) / 86400000 + 1) / 7);
  return { week, year: dt.getUTCFullYear() };
}

/** 星期几，0 = 周日，跟 Date.getDay() 一致 */
export function weekday(date: string): number {
  const [y, m, d] = date.split('-').map(Number);
  return new Date(Date.UTC(y, m - 1, d)).getUTCDay();
}

