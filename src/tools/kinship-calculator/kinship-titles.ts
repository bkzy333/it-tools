export const KINSHIP_TITLES: readonly string[] = [...new Set(RAW_KINSHIP_TITLES)];

export interface KinshipTitleSuggestion {
  /** 下拉框要展示的候选（已按「完全相同 → 以输入开头 → 仅包含」排序，并被 limit 截断） */
  items: string[];
  /** 命中总数，用于提示「还有 N 个，继续输入缩小范围」 */
  total: number;
}

/**
 * 按输入内容筛候选称呼。
 *
 * 排序分三层，越靠前越「像用户想打的」：
 *   1. 与输入完全相同（用户已经打全了，置顶让他知道这条有效）
 *   2. 以输入开头（打「舅」时「舅舅」「舅父」「舅母」优先）
 *   3. 仅包含输入（打「舅」时的「大舅」「大舅妈」）
 * 同层内保持候选表的原始顺序（即常用度），不做字典序重排。
 */
export function suggestKinshipTitles(query: string, limit = 12): KinshipTitleSuggestion {
  const keyword = query.trim();
  if (!keyword) {
    return { items: [], total: 0 };
  }

  const exact: string[] = [];
  const startsWith: string[] = [];
  const includes: string[] = [];

  for (const title of KINSHIP_TITLES) {
    if (title === keyword) {
      exact.push(title);
    } else if (title.startsWith(keyword)) {
      startsWith.push(title);
    } else if (title.includes(keyword)) {
      includes.push(title);
    }
  }

  const matched = [...exact, ...startsWith, ...includes];
  return { items: matched.slice(0, limit), total: matched.length };
}
