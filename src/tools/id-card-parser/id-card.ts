export interface IdCardInfo {
  /** 是否通过校验位验证 */
  valid: boolean;
  /** 不通过的原因，通过时为空 */
  reason: string;
  /** 归一化后的 18 位号码（15 位会自动升级） */
  normalized: string;
  /** 输入的是不是 15 位老号码 */
  wasOldFormat: boolean;
  region: string;
  birthday: string;
  gender: string;
  age: number | null;
  zodiac: string;
  constellation: string;
  /** 校验位，用于展示算法过程 */
  expectedCheckCode: string;
}

/** 由前 17 位算出第 18 位校验码 */
export function computeCheckCode(first17: string): string {
  let sum = 0;
  for (let i = 0; i < 17; i += 1) {
    sum += Number(first17[i]) * WEIGHTS[i];
  }
  return CHECK_CODES[sum % 11];
}

/** 15 位老号码升到 18 位 */
export function upgrade15To18(id15: string): string {
  const body = `${id15.slice(0, 6)}19${id15.slice(6)}`;
  return `${body}${computeCheckCode(body)}`;
}

function regionOf(code6: string): string {
  const province = PROVINCES[code6.slice(0, 2)];
  if (!province) {
    return '未知地区（行政区划码未收录）';
  }
  const city = CITIES[code6.slice(0, 4)];
  return city ? `${province} ${city}` : province;
}

function constellationOf(month: number, day: number): string {
  for (const item of CONSTELLATIONS) {
    const [fromMonth, fromDay] = item.from;
    const [toMonth, toDay] = item.to;
    // 摩羯座跨年，单独处理
    if (fromMonth > toMonth) {
      if ((month === fromMonth && day >= fromDay) || (month === toMonth && day <= toDay) || month > fromMonth || month < toMonth) {
        return item.name;
      }
      continue;
    }
    if (
      (month === fromMonth && day >= fromDay) ||
      (month === toMonth && day <= toDay) ||
      (month > fromMonth && month < toMonth)
    ) {
      return item.name;
    }
  }
  return '摩羯座';
}

function ageOf(birth: Date): number {
  const now = new Date();
  let age = now.getFullYear() - birth.getFullYear();
  const beforeBirthday =
    now.getMonth() < birth.getMonth() ||
    (now.getMonth() === birth.getMonth() && now.getDate() < birth.getDate());
  if (beforeBirthday) {
    age -= 1;
  }
  return age;
}

const EMPTY: IdCardInfo = {
  valid: false,
  reason: '',
  normalized: '',
  wasOldFormat: false,
  region: '',
  birthday: '',
  gender: '',
  age: null,
  zodiac: '',
  constellation: '',
  expectedCheckCode: '',
};

/**
 * 校验并解析一个身份证号。
 * 返回的对象里 valid 只代表"校验位算得对"，不代表这个号真的存在——
 * 这个区别必须让用户在页面上看到，否则就成了"查人"工具。
 */
export function parseIdCard(raw: string): IdCardInfo {
  const input = raw.trim().toUpperCase().replace(/\s/g, '');

  if (!input) {
    return { ...EMPTY, reason: '请输入身份证号' };
  }

  let id = input;
  const wasOldFormat = id.length === 15;

  if (wasOldFormat) {
    if (!/^\d{15}$/.test(id)) {
      return { ...EMPTY, reason: '15 位号码里出现了非数字字符' };
    }
    id = upgrade15To18(id);
  }

  if (id.length !== 18) {
    return { ...EMPTY, reason: `号码长度是 ${id.length} 位，应为 18 位（或 15 位老号码）` };
  }
  if (!/^\d{17}[\dX]$/.test(id)) {
    return { ...EMPTY, reason: '前 17 位必须是数字，最后一位是数字或 X' };
  }

  const birthdayText = id.slice(6, 14);
  const year = Number(birthdayText.slice(0, 4));
  const month = Number(birthdayText.slice(4, 6));
  const day = Number(birthdayText.slice(6, 8));
  const birth = new Date(year, month - 1, day);
  const dateOk =
    birth.getFullYear() === year && birth.getMonth() === month - 1 && birth.getDate() === day;

  if (!dateOk) {
    return { ...EMPTY, normalized: id, wasOldFormat, reason: '出生日期部分不是合法日期' };
  }
  if (year < 1900 || birth.getTime() > Date.now()) {
    return { ...EMPTY, normalized: id, wasOldFormat, reason: '出生日期不在合理范围内' };
  }

  const expectedCheckCode = computeCheckCode(id.slice(0, 17));
  const valid = expectedCheckCode === id[17];

  const genderDigit = Number(id[16]);

  return {
    valid,
    reason: valid ? '' : `校验位应为 ${expectedCheckCode}，实际是 ${id[17]}`,
    normalized: id,
    wasOldFormat,
    region: regionOf(id.slice(0, 6)),
    birthday: `${year}-${String(month).padStart(2, '0')}-${String(day).padStart(2, '0')}`,
    gender: genderDigit % 2 === 1 ? '男' : '女',
    age: ageOf(birth),
    zodiac: ZODIACS[(year - 1900) % 12],
    constellation: constellationOf(month, day),
    expectedCheckCode,
  };
}
